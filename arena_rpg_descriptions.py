def skill_description(skill, source):
    key=source.get('archclass_id')
    if (key not in BRANCH_SKILLS or skill.class_id!=source.get('class_id')
            or skill.skill_id not in BRANCH_SKILLS[key] and skill.skill_id!='arch_'+key):
        return skill.description
    return FINAL_SKILLS.get(skill.name) or BRANCH_SKILLS.get(source.get('archclass_id'),{}).get(skill.skill_id) or skill.description


def branch_skill_info(skill, source, target=None):
    from arena_rpg import branch, rpg_variant
    key=branch(source)
    if skill.skill_id not in BRANCH_SKILLS.get(key,{}):return None
    actor=dict(source,effects=source.get('effects',[]),rpg_state=source.get('rpg_state',{}))
    enemy=target or dict(hp=100,stats=dict(max_hp=100),effects=[])
    variant=rpg_variant(skill,actor,enemy)
    return dict(name=variant.name,min_level=max(10,skill.unlock_level),condition='Вариант навыка выбранного архикласса.',
                description=skill_description(variant,source),cost=variant.cost,power=variant.power,
                active=False,specialization=True)
