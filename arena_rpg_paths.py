def is_final(source):
    return source.get('level', 0) >= 20 and source.get('archclass_stage', 20) >= 20


def path_milestones(source):
    entry = PATHS[source['archclass_id']]
    return [dict(level=level, description=entry[index], unlocked=source['level'] >= level,
                 **({'skill_id': 'arch_' + source['archclass_id']} if level == 15 else {}))
            for level, index in ((12, 2), (15, 3), (18, 4))]
